// CREAR BORDES COMPARTIDOS

function crearBordes() {
    const horizontales = [];
    const verticales = [];

    for (let fila = 0; fila < FILAS - 1; fila++) {
        horizontales[fila] = [];

        for (let columna = 0; columna < COLUMNAS; columna++) {
            horizontales[fila][columna] =
                Math.random() < 0.5 ? 1 : -1;
        }
    }

    for (let fila = 0; fila < FILAS; fila++) {
        verticales[fila] = [];

        for (let columna = 0; columna < COLUMNAS - 1; columna++) {
            verticales[fila][columna] =
                Math.random() < 0.5 ? 1 : -1;
        }
    }

    return { horizontales, verticales };
}


// BORDES HORIZONTALES

function bordeHorizontal(x1, x2, y, salida) {
    if (salida === 0) {
        return "L " + x2 + " " + y;
    }

    const medio = (x1 + x2) / 2;
    const direccion = x2 > x1 ? 1 : -1;

    return [
        "L " + (medio - 13 * direccion) + " " + y,
        "C " + (medio - 13 * direccion) + " " + (y + salida * 2) +
        ", " + (medio - 13 * direccion) + " " + (y + salida * 10) +
        ", " + medio + " " + (y + salida * 10),
        "C " + (medio + 13 * direccion) + " " + (y + salida * 10) +
        ", " + (medio + 13 * direccion) + " " + (y + salida * 2) +
        ", " + (medio + 13 * direccion) + " " + y,
        "L " + x2 + " " + y
    ].join(" ");
}


// BORDES VERTICALES

function bordeVertical(y1, y2, x, salida) {
    if (salida === 0) {
        return "L " + x + " " + y2;
    }

    const medio = (y1 + y2) / 2;
    const direccion = y2 > y1 ? 1 : -1;

    return [
        "L " + x + " " + (medio - 13 * direccion),
        "C " + (x + salida * 2) + " " + (medio - 13 * direccion) +
        ", " + (x + salida * 10) + " " + (medio - 13 * direccion) +
        ", " + (x + salida * 10) + " " + medio,
        "C " + (x + salida * 10) + " " + (medio + 13 * direccion) +
        ", " + (x + salida * 2) + " " + (medio + 13 * direccion) +
        ", " + x + " " + (medio + 13 * direccion),
        "L " + x + " " + y2
    ].join(" ");
}


// FORMA DE LA PIEZA

function crearCamino(arriba, derecha, abajo, izquierda) {
    let camino = "M 13 13";

    camino += bordeHorizontal(13, 65, 13, -arriba);
    camino += bordeVertical(13, 65, 65, derecha);
    camino += bordeHorizontal(65, 13, 65, abajo);
    camino += bordeVertical(65, 13, 13, -izquierda);

    return camino + " Z";
}


// SISTEMA DE MOVIMIENTO CON EL RATÓN

function activarMovimiento(pieza) {
    pieza.draggable = false;
    pieza.style.touchAction = "none";

    pieza.addEventListener("pointerdown", function (evento) {
        if (pieza.classList.contains("colocada")) return;
        if (evento.button !== 0 && evento.pointerType === "mouse") return;
        if (movimientoActual) return;

        const rect = pieza.getBoundingClientRect();

        movimientoActual = {
            pieza: pieza,
            inicioX: evento.clientX,
            inicioY: evento.clientY,
            offsetX: evento.clientX - rect.left,
            offsetY: evento.clientY - rect.top,
            rect: rect,
            movida: false,
            estilosOriginales: pieza.style.cssText
        };

        evento.preventDefault();
    });
}


// MOVER LA PIEZA CON EL PUNTERO

document.addEventListener("pointermove", function (evento) {
    if (!movimientoActual) return;

    const movimiento = movimientoActual;

    const diferenciaX = evento.clientX - movimiento.inicioX;
    const diferenciaY = evento.clientY - movimiento.inicioY;

    // Evita confundir un clic con un desplazamiento

    if (
        !movimiento.movida &&
        Math.hypot(diferenciaX, diferenciaY) < 5
    ) {
        return;
    }

    movimiento.movida = true;

    const pieza = movimiento.pieza;

    if (!pieza.classList.contains("arrastrando")) {
        pieza.classList.add("arrastrando");

        pieza.style.position = "fixed";
        pieza.style.left = "0px";
        pieza.style.top = "0px";
        pieza.style.width = movimiento.rect.width + "px";
        pieza.style.height = movimiento.rect.height + "px";
        pieza.style.margin = "0";
        pieza.style.zIndex = "99999";
        pieza.style.pointerEvents = "none";
        pieza.style.transform = "none";
    }

    pieza.style.left =
        (evento.clientX - movimiento.offsetX) + "px";

    pieza.style.top =
        (evento.clientY - movimiento.offsetY) + "px";
});


// SOLTAR LA PIEZA

document.addEventListener("pointerup", function (evento) {
    if (!movimientoActual) return;

    const movimiento = movimientoActual;
    const pieza = movimiento.pieza;

    movimientoActual = null;

    pieza.classList.remove("arrastrando");

    if (movimiento.movida) {
        // Averiguar qué elemento está debajo del ratón

        const elemento = document.elementFromPoint(
            evento.clientX,
            evento.clientY
        );

        const celda = elemento
            ? elemento.closest(".celda")
            : null;

        // Restaurar los estilos antes de colocarla

        pieza.style.cssText = movimiento.estilosOriginales;

        const numeroPieza = Number(pieza.dataset.numero);

        if (
            celda &&
            Number(celda.dataset.numero) === numeroPieza &&
            !celda.querySelector(".colocada")
        ) {
            colocarPieza(pieza, celda);
        }

    } else {
        // Si solo hizo clic, seleccionar la pieza

        pieza.style.cssText = movimiento.estilosOriginales;

        if (piezaSeleccionada) {
            piezaSeleccionada.classList.remove("seleccionada");
        }

        if (piezaSeleccionada === pieza) {
            piezaSeleccionada = null;
        } else {
            piezaSeleccionada = pieza;
            pieza.classList.add("seleccionada");
        }
    }
});


// CREAR UNA PIEZA

function crearPieza(numero, imagen, bordes) {
    const fila = Math.floor(numero / COLUMNAS);
    const columna = numero % COLUMNAS;

    const arriba = fila === 0
        ? 0
        : -bordes.horizontales[fila - 1][columna];

    const derecha = columna === COLUMNAS - 1
        ? 0
        : bordes.verticales[fila][columna];

    const abajo = fila === FILAS - 1
        ? 0
        : bordes.horizontales[fila][columna];

    const izquierda = columna === 0
        ? 0
        : -bordes.verticales[fila][columna - 1];

    const camino = crearCamino(
        arriba,
        derecha,
        abajo,
        izquierda
    );

    const pieza = document.createElement("div");

    pieza.className = "pieza";
    pieza.dataset.numero = numero;

    const id = "recorte-" + nivelActual + "-" + numero;

    pieza.innerHTML = [
        '<svg viewBox="0 0 78 78">',
        '<defs>',
        '<clipPath id="' + id + '">',
        '<path d="' + camino + '"></path>',
        '</clipPath>',
        '</defs>',
        '<image href="' + imagen + '"',
        'x="' + (MARGEN - columna * LADO) + '"',
        'y="' + (MARGEN - fila * LADO) + '"',
        'width="' + (LADO * COLUMNAS) + '"',
        'height="' + (LADO * FILAS) + '"',
        'preserveAspectRatio="xMidYMid slice"',
        'clip-path="url(#' + id + ')">',
        '</image>',
        '<path d="' + camino + '"',
        'fill="none" stroke="#ffffff" stroke-width="1.5">',
        '</path>',
        '</svg>'
    ].join("");

    activarMovimiento(pieza);

    return pieza;
}


// CARGAR NIVEL

function cargarNivel(numeroNivel) {
    if (numeroNivel < 0 || numeroNivel >= niveles.length) return;

    if (temporizadorVictoria !== null) {
        clearTimeout(temporizadorVictoria);
        temporizadorVictoria = null;
    }

    nivelActual = numeroNivel;
    piezasColocadas = 0;
    piezaSeleccionada = null;
    movimientoActual = null;

    const nivel = niveles[nivelActual];

    tablero.innerHTML = "";
    bandeja.innerHTML = "";

    zonaPiezas.classList.remove("oculto");
    cartaFinal.classList.add("oculto");
    botonSiguiente.classList.add("oculto");

    imagenReferencia.onerror = function () {
        alert("No se encontró la imagen: " + nivel.imagen);
    };

    imagenReferencia.src = nivel.imagen;

    nivelTexto.textContent =
        "Rompecabezas " + (nivelActual + 1) + " de " + niveles.length;

    actualizarProgreso();

    // CREAR LAS 36 CELDAS

    for (let numero = 0; numero < TOTAL; numero++) {
        const celda = document.createElement("div");

        celda.className = "celda";
        celda.dataset.numero = numero;

        celda.addEventListener("click", function () {
            if (!piezaSeleccionada) return;

            const numeroPieza = Number(
                piezaSeleccionada.dataset.numero
            );

            if (
                numeroPieza === Number(celda.dataset.numero) &&
                !celda.querySelector(".colocada")
            ) {
                colocarPieza(piezaSeleccionada, celda);
            }
        });

        tablero.appendChild(celda);
    }

    // CREAR PIEZAS MEZCLADAS

    const bordes = crearBordes();

    const numeros = Array.from(
        { length: TOTAL },
        function (_, i) {
            return i;
        }
    );

    for (let i = numeros.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));

        [numeros[i], numeros[j]] = [numeros[j], numeros[i]];
    }

    numeros.forEach(function (numero) {
        bandeja.appendChild(
            crearPieza(numero, nivel.imagen, bordes)
        );
    });
}


// COLOCAR PIEZA

function colocarPieza(pieza, celda) {
    if (!pieza || !celda) return;
    if (pieza.classList.contains("colocada")) return;
    if (celda.querySelector(".colocada")) return;

    const numeroPieza = Number(pieza.dataset.numero);
    const numeroCelda = Number(celda.dataset.numero);

    if (numeroPieza !== numeroCelda) return;

    pieza.classList.remove("seleccionada");
    pieza.classList.add("colocada");

    pieza.style.position = "";
    pieza.style.left = "";
    pieza.style.top = "";
    pieza.style.width = "";
    pieza.style.height = "";
    pieza.style.margin = "";
    pieza.style.zIndex = "";
    pieza.style.pointerEvents = "";
    pieza.style.transform = "";

    piezaSeleccionada = null;

    celda.appendChild(pieza);

    piezasColocadas++;

    actualizarProgreso();
    comprobarVictoria();
}


// ACTUALIZAR PROGRESO

function actualizarProgreso() {
    progreso.textContent =
        "Piezas: " + piezasColocadas + " / " + TOTAL;

    const porcentajeActual = Math.round(
        (piezasColocadas / TOTAL) * 100
    );

    porcentaje.textContent = porcentajeActual + "%";
}


// COMPROBAR VICTORIA

function comprobarVictoria() {
    if (piezasColocadas !== TOTAL) return;

    temporizadorVictoria = setTimeout(function () {
        zonaPiezas.classList.add("oculto");
        cartaFinal.classList.remove("oculto");

        const nivel = niveles[nivelActual];

        tituloCarta.textContent = nivel.titulo;
        mensajeCarta.textContent = nivel.mensaje;

        if (nivelActual < niveles.length - 1) {
            botonSiguiente.classList.remove("oculto");
        } else {
            botonSiguiente.classList.add("oculto");
        }

        temporizadorVictoria = null;
    }, 700);
}


// SIGUIENTE ROMPECABEZAS

botonSiguiente.addEventListener("click", function () {
    if (nivelActual < niveles.length - 1) {
        cargarNivel(nivelActual + 1);
    }
});


// REINICIAR NIVEL

botonReiniciar.addEventListener("click", function () {
    cargarNivel(nivelActual);
});
